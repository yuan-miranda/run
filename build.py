import os
import shutil
import subprocess
import sys


def load_env(file_path):
    """Load key-value pairs from .env without external dependencies."""
    if not os.path.exists(file_path):
        return
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    k, v = line.split("=", 1)
                    os.environ.setdefault(k.strip(), v.strip().strip("'\""))
    except Exception:
        pass


def build():
    root_dir = os.path.dirname(os.path.abspath(__file__))
    dist_dir = os.path.join(root_dir, "dist")
    build_dir = os.path.join(root_dir, "build")
    config_file = os.path.join(root_dir, "client_config.py")

    # Load secrets from .env if available without external dependency
    load_env(os.path.join(root_dir, ".env"))

    client_key = os.getenv("DASHBOARD_PASSWORD", "DEFAULT_SECRET")

    git_sha = os.getenv("CLIENT_VERSION")
    if not git_sha:
        try:
            git_sha = (
                subprocess.check_output(
                    ["git", "rev-parse", "--short", "HEAD"],
                    cwd=root_dir,
                    stderr=subprocess.DEVNULL,
                )
                .decode("utf-8")
                .strip()
            )
        except Exception:
            git_sha = "dev"
    else:
        git_sha = git_sha[:7]

    print(f"[Build] Etching CLIENT_KEY and CLIENT_VERSION ({git_sha}) into binary build config...")
    with open(config_file, "w", encoding="utf-8") as f:
        f.write(
            f"# Generated by build.py - DO NOT COMMIT TO GIT\n"
            f"CLIENT_KEY = {repr(client_key)}\n"
            f"CLIENT_VERSION = {repr(git_sha)}\n"
        )

    try:
        print("[Build] Installing dependencies from requirements.txt...")
        subprocess.check_call(
            [sys.executable, "-m", "pip", "install", "-r", "requirements.txt"]
        )

        run_bin = "run.exe"
        installer_bin = "installer.exe"

        print(f"\n[Build] Compiling client.py -> {run_bin}...")
        subprocess.check_call(
            [
                sys.executable,
                "-m",
                "PyInstaller",
                "--noconsole",
                "--onefile",
                "--clean",
                "-n",
                "run",
                "client.py",
            ],
            cwd=root_dir,
        )

        print(f"\n[Build] Compiling installer.py -> {installer_bin}...")
        subprocess.check_call(
            [
                sys.executable,
                "-m",
                "PyInstaller",
                "--noconsole",
                "--onefile",
                "--clean",
                "-n",
                "installer",
                "installer.py",
            ],
            cwd=root_dir,
        )

        run_dist = os.path.join(dist_dir, run_bin)
        installer_dist = os.path.join(dist_dir, installer_bin)

        run_target = os.path.join(root_dir, run_bin)
        installer_target = os.path.join(root_dir, installer_bin)

        if os.path.exists(run_dist):
            shutil.copy2(run_dist, run_target)
            print(f"[Build] Successfully copied {run_bin} to root -> {run_target}")

        if os.path.exists(installer_dist):
            shutil.copy2(installer_dist, installer_target)
            print(
                f"[Build] Successfully copied {installer_bin} to root -> {installer_target}"
            )

    finally:
        print("\n[Build] Cleaning up temporary build artifacts and etched config...")
        if os.path.exists(config_file):
            os.remove(config_file)
            print(f"[Build] Removed temporary {config_file}")
        if os.path.exists(build_dir):
            shutil.rmtree(build_dir, ignore_errors=True)
        if os.path.exists(dist_dir):
            shutil.rmtree(dist_dir, ignore_errors=True)

        for spec in ["run.spec", "installer.spec"]:
            spec_path = os.path.join(root_dir, spec)
            if os.path.exists(spec_path):
                os.remove(spec_path)

    print(
        "\n[Build Complete] Both run.exe and installer.exe are ready!"
    )


if __name__ == "__main__":
    build()
